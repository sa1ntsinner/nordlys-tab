window.I18N = {
  translations,
  currentLang: 'en',

  t(key, params = {}) {
    let text = this.translations[this.currentLang]?.[key] || this.translations['en']?.[key] || key;
    if (typeof text === 'string') {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
      }
    }
    return text;
  },

  setLanguage(lang) {
    this.currentLang = this.translations[lang] ? lang : 'en';
    try {
      localStorage.setItem('aurora_language', this.currentLang);
    } catch(e) {}
    this.applyDOM();
    window.dispatchEvent(new CustomEvent('aurora:languagechange', { detail: { lang: this.currentLang } }));
  },

  applyDOM(root = document) {
    // 1. Elements with data-i18n (textContent / innerText)
    root.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('placeholder')) el.setAttribute('placeholder', text);
      } else {
        el.textContent = text;
      }
    });

    // 2. Placeholders
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', this.t(key));
    });

    // 3. Titles / Tooltips
    root.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.setAttribute('title', this.t(key));
    });

    // 4. Aria labels
    root.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      el.setAttribute('aria-label', this.t(key));
    });
  }
};
